export function getModuleBySlug(slug: string): ProductModule | undefined {
  return modulesCatalog.find((m) => m.slug === slug);
}

export function getRelatedModules(module: ProductModule): ProductModule[] {
  return module.related
    .map((slug) => getModuleBySlug(slug))
    .filter((m): m is ProductModule => Boolean(m));
}

export function getNextModule(slug: string): ProductModule | undefined {
  const index = modulesCatalog.findIndex((m) => m.slug === slug);
  if (index < 0) return undefined;
  return modulesCatalog[(index + 1) % modulesCatalog.length];
}

export function resolveModuleScreen(screenId: ProductScreenId) {
  return productScreens[screenId];
}

export const moduleSlugs = modulesCatalog.map((m) => m.slug);

/** Visible FAQ / points for production (hides placeholder: true). */
export function visibleModulePoints<T extends { placeholder?: boolean }>(
  items: T[],
): T[] {
  return items.filter((item) => !item.placeholder);
}

/** First three non-placeholder feature titles for home / hub cards. */
export function getModuleCardFeatures(
  module: ProductModule,
  limit = 3,
): string[] {
  return module.featureGroups
    .flatMap((group) => group.items)
    .filter((item) => !item.placeholder)
    .slice(0, limit)
    .map((item) => item.title);
}

/** First non-placeholder whyConnect point for card teaser. */
export function getModulePrimaryWhy(
  module: ProductModule,
): ModulePoint | undefined {
  return visibleModulePoints(module.whyConnect)[0];
}
